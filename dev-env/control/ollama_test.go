package main

import "testing"

// A copy number below 0 names no blob, so it is a config error.
func TestOllama_RejectsANegativeCopy(t *testing.T) {
	_, err := writeConfig(t, "  ollama: {models: [{id: m, file: a.gguf, copy: -1}]}\n")
	wantError(t, err, "negative copy")
}

// A model's blob and num_ctx come from its modelfile, as /api/show returns
// it (0.40.8); a modelfile without num_ctx reads as 0, so it never matches.
func TestModelfileFacts(t *testing.T) {
	modelfile := "# Modelfile generated by \"ollama show\"\nFROM /root/.ollama/models/blobs/sha256-5385\nTEMPLATE {{ .Prompt }}\nPARAMETER num_ctx 4096\n"
	if digest, ctxSize := modelfileFacts(modelfile); digest != "sha256:5385" || ctxSize != 4096 {
		t.Errorf("got %q and %d, want 'sha256:5385' and 4096", digest, ctxSize)
	}
	if _, ctxSize := modelfileFacts("FROM /root/.ollama/models/blobs/sha256-5385\n"); ctxSize != 0 {
		t.Errorf("got num_ctx %d without a PARAMETER line, want 0", ctxSize)
	}
}
